def set_para_format(para, first_line=True):
    pf = para.paragraph_format
    if first_line:
        pf.first_line_indent = Cm(1.25)
    pf.space_before = Pt(0)
    pf.space_after = Pt(6)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.5


def abzac(doc, text, bold=False, indent=True,
          align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    p = doc.add_paragraph()
    p.alignment = align
    set_para_format(p, first_line=indent)
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(14)
    r.font.name = 'Times New Roman'
    return p


def zagolovok(doc, text, center=True):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    pf = p.paragraph_format
    pf.space_before = Pt(12)
    pf.space_after = Pt(6)
    pf.first_line_indent = Cm(0)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(14)
    r.font.name = 'Times New Roman'
    return p


def podrazdel(doc, text):
    return zagolovok(doc, text, center=False)


def punkt(doc, text):
    """Абзац-пункт со знаком тире и красной строкой."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(3)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.5
    r = p.add_run('— ' + text)
    r.font.size = Pt(14)
    r.font.name = 'Times New Roman'
    return p


def numer(doc, num, text):
    """Нумерованный пункт."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(3)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.5
    r = p.add_run(f'{num}. {text}')
    r.font.size = Pt(14)
    r.font.name = 'Times New Roman'
    return p


