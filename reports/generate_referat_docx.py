def font(size: int, bold: bool = False):
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
    ]
    for candidate in candidates:
        if Path(candidate).exists():
            return ImageFont.truetype(candidate, size)
    return ImageFont.load_default()


def draw_box(draw, xy, text, fill="#eef4ff", outline="#315a9f"):
    x1, y1, x2, y2 = xy
    draw.rounded_rectangle(xy, radius=18, fill=fill, outline=outline, width=3)
    lines = []
    for part in text.split("\n"):
        lines.extend(wrap(part, width=22) or [""])
    y = y1 + 14
    f = font(22)
    for line in lines[:4]:
        bbox = draw.textbbox((0, 0), line, font=f)
        draw.text(((x1 + x2 - bbox[2]) / 2, y), line, fill="#10213f", font=f)
        y += 28


def draw_arrow(draw, start, end):
    draw.line([start, end], fill="#1f3f75", width=4)
    ex, ey = end
    sx, sy = start
    if abs(ex - sx) > abs(ey - sy):
        sign = 1 if ex > sx else -1
        points = [(ex, ey), (ex - 16 * sign, ey - 9), (ex - 16 * sign, ey + 9)]
    else:
        sign = 1 if ey > sy else -1
        points = [(ex, ey), (ex - 9, ey - 16 * sign), (ex + 9, ey - 16 * sign)]
    draw.polygon(points, fill="#1f3f75")


def make_diagram(filename, title, boxes, arrows):
    ASSETS_DIR.mkdir(parents=True, exist_ok=True)
    img = Image.new("RGB", (1400, 850), "#ffffff")
    draw = ImageDraw.Draw(img)
    title_font = font(34, bold=True)
    draw.text((60, 34), title, fill="#10213f", font=title_font)
    for box in boxes:
        draw_box(draw, box["xy"], box["text"], box.get("fill", "#eef4ff"))
    for arrow in arrows:
        draw_arrow(draw, arrow[0], arrow[1])
    path = ASSETS_DIR / filename
    img.save(path)
    return path


